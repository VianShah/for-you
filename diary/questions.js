// Same question for both phones on the same day. All topics are shuffled together into
// one fixed order, and each day moves one step along it, so nothing repeats until every
// question has had its day.
function todaysQuestion(date = new Date(), list = []) {
  const [y, m, d] = date.toLocaleDateString("en-CA").split("-").map(Number); // local date
  const dayNumber = Math.floor(Date.UTC(y, m - 1, d) / 864e5);
  const scramble = s => { let h = hash(s); h ^= h >>> 16; h = Math.imul(h, 0x85ebca6b); h ^= h >>> 13; h = Math.imul(h, 0xc2b2ae35); return (h ^ (h >>> 16)) >>> 0; };
  const order = liveQuestions(list).sort((a, b) => scramble(a.id) - scramble(b.id));
  return order[dayNumber % order.length];
}
